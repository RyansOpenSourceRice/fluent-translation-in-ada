#!/usr/bin/env python3
"""Generate Fixture_Expectations Ada package from upstream fixture JSON.

Usage: generate_expectations.py <fixtures-json-dir> <out-dir> [--defer name ...]

--defer marks fixtures whose entry structure needs real pattern parsing
(M1b); the driver skips them with the given reason embedded in the name
as name:reason.
"""
import json
import sys

KIND_MAP = {
    "Message": "Message",
    "Term": "Term",
    "Comment": "Comment",
    "GroupComment": "Group_Comment",
    "ResourceComment": "Resource_Comment",
    "Junk": "Junk",
}


def ada_str(s):
    return '"' + s.replace('"', '""') + '"'


def main():
    args = sys.argv[1:]
    if len(args) < 2:
        print(__doc__)
        return 1
    src_dir, out_dir = args[0], args[1]
    defers = {}
    for d in args[2:]:
        assert d.startswith("--defer="), d
        name, _, reason = d[len("--defer="):].partition(":")
        defers[name] = reason or "deferred to M1b"

    import glob
    import os
    names = sorted(
        os.path.basename(f)[:-5]
        for f in glob.glob(os.path.join(src_dir, "*.json"))
    )

    spec = []
    body = []
    spec.append("--  Generated by tests/generate_expectations.py - do not edit.")
    spec.append("--  Source: upstream projectfluent/fluent test/fixtures/*.json.")
    spec.append("with Fluent.Syntax;")
    spec.append("package Fixture_Expectations is")
    spec.append("   function Fixture_Count return Natural;")
    spec.append("   function Fixture_Name (I : Positive) return String;")
    spec.append("   function Fixture_Active (I : Positive) return Boolean;")
    spec.append("   function Fixture_Reason (I : Positive) return String;")
    spec.append("   function Fixture_Length (I : Positive) return Natural;")
    spec.append(
        "   function Fixture_Kind (I, K : Positive)"
        " return Fluent.Syntax.Entry_Kind;"
    )
    spec.append("   function Fixture_Id (I, K : Positive) return String;")
    spec.append("end Fixture_Expectations;")

    body.append("--  Generated by tests/generate_expectations.py - do not edit.")
    body.append("package body Fixture_Expectations is")
    body.append("   use Fluent.Syntax;")
    body.append(f"   function Fixture_Count return Natural is ({len(names)});")
    body.append("   function Fixture_Name (I : Positive) return String is")
    body.append("   begin")
    for i, n in enumerate(names, 1):
        body.append(f"      if I = {i} then return {ada_str(n)}; end if;")
    body.append('      return "";')
    body.append("   end Fixture_Name;")
    body.append("   function Fixture_Active (I : Positive) return Boolean is")
    body.append("   begin")
    for i, n in enumerate(names, 1):
        if n in defers:
            body.append(f"      if I = {i} then return False; end if;")
    body.append("      return True;")
    body.append("   end Fixture_Active;")
    body.append("   function Fixture_Reason (I : Positive) return String is")
    body.append("   begin")
    for i, n in enumerate(names, 1):
        if n in defers:
            body.append(
                f"      if I = {i} then return {ada_str(defers[n])}; end if;"
            )
    body.append('      return "";')
    body.append("   end Fixture_Reason;")

    entries = {}
    for n in names:
        with open(os.path.join(src_dir, n + ".json")) as f:
            d = json.load(f)
        entries[n] = [
            (KIND_MAP[e["type"]], (e.get("id") or {}).get("name", ""))
            for e in d["body"]
        ]

    body.append("   function Fixture_Length (I : Positive) return Natural is")
    body.append("   begin")
    for i, n in enumerate(names, 1):
        body.append(f"      if I = {i} then return {len(entries[n])}; end if;")
    body.append("      return 0;")
    body.append("   end Fixture_Length;")
    body.append(
        "   function Fixture_Kind (I, K : Positive)"
        " return Fluent.Syntax.Entry_Kind is"
    )
    body.append("   begin")
    for i, n in enumerate(names, 1):
        for k, (t, _) in enumerate(entries[n], 1):
            body.append(
                f"      if I = {i} and then K = {k} then return {t}; end if;"
            )
    body.append("      return Blank;")
    body.append("   end Fixture_Kind;")
    body.append("   function Fixture_Id (I, K : Positive) return String is")
    body.append("   begin")
    for i, n in enumerate(names, 1):
        for k, (_, ident) in enumerate(entries[n], 1):
            if ident:
                body.append(
                    f"      if I = {i} and then K = {k}"
                    f" then return {ada_str(ident)}; end if;"
                )
    body.append('      return "";')
    body.append("   end Fixture_Id;")
    body.append("end Fixture_Expectations;")

    with open(os.path.join(out_dir, "fixture_expectations.ads"), "w") as f:
        f.write("\n".join(spec) + "\n")
    with open(os.path.join(out_dir, "fixture_expectations.adb"), "w") as f:
        f.write("\n".join(body) + "\n")
    active = sum(1 for n in names if n not in defers)
    print(f"fixtures: {len(names)}, active: {active}, "
          f"deferred: {len(defers)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
